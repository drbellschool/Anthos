-- Server-only generative story outcomes, one canonical result per chapter and room.
alter table public.anthos_pilot_rooms
 add column if not exists resolving_chapter smallint not null default 0;
alter table public.anthos_pilot_rooms
 add constraint anthos_pilot_resolving_chapter_check check (resolving_chapter between 0 and 8);
create table if not exists public.anthos_pilot_chapter_outcomes (
 room_id uuid not null references public.anthos_pilot_rooms(id) on delete cascade,
 chapter_number smallint not null check (chapter_number between 1 and 8),
 consequence text not null check (char_length(consequence) between 35 and 1800),
 next_scene text check (next_scene is null or char_length(next_scene) between 60 and 2200),
 lens text not null check (lens in ('gottman','schnarch','aron')),
 created_at timestamptz not null default now(),
 primary key(room_id,chapter_number)
);
alter table public.anthos_pilot_chapter_outcomes enable row level security;
revoke all on public.anthos_pilot_chapter_outcomes from public,anon,authenticated;
grant select,insert,update,delete on public.anthos_pilot_chapter_outcomes to service_role;
comment on table public.anthos_pilot_chapter_outcomes is 'Shared OpenAI-authored branch effects, private room only; generated by server with user consent.';
